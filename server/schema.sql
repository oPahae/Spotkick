CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  username VARCHAR(16) NOT NULL,
  passwordHash VARCHAR(100) NOT NULL,
  sex ENUM('male','female') NOT NULL,
  image MEDIUMTEXT NULL,
  score INT NOT NULL DEFAULT 0,
  wins INT UNSIGNED NOT NULL DEFAULT 0,
  losses INT UNSIGNED NOT NULL DEFAULT 0,
  matchesPlayed INT UNSIGNED NOT NULL DEFAULT 0,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uniqUsername (username),
  KEY idxUsersScore (score, wins)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS matches (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  status ENUM('WAITING','IN_PROGRESS','FINISHED','CANCELLED') NOT NULL DEFAULT 'WAITING',
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  startedAt TIMESTAMP NULL DEFAULT NULL,
  finishedAt TIMESTAMP NULL DEFAULT NULL,
  winnerId INT UNSIGNED NULL,
  endReason VARCHAR(16) NULL,
  totalRounds INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  KEY idxMatchesStatus (status),
  CONSTRAINT fkMatchesWinner FOREIGN KEY (winnerId) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS matchPlayers (
  matchId INT UNSIGNED NOT NULL,
  playerId INT UNSIGNED NOT NULL,
  slot TINYINT UNSIGNED NOT NULL,
  score INT UNSIGNED NOT NULL DEFAULT 0,
  goals INT UNSIGNED NOT NULL DEFAULT 0,
  saves INT UNSIGNED NOT NULL DEFAULT 0,
  misses INT UNSIGNED NOT NULL DEFAULT 0,
  pointsAwarded INT NOT NULL DEFAULT 0,
  PRIMARY KEY (matchId, playerId),
  UNIQUE KEY uniqMatchSlot (matchId, slot),
  KEY idxMatchPlayersPlayer (playerId),
  CONSTRAINT chkMatchSlot CHECK (slot IN (0, 1)),
  CONSTRAINT fkMatchPlayersMatch FOREIGN KEY (matchId) REFERENCES matches (id) ON DELETE CASCADE,
  CONSTRAINT fkMatchPlayersPlayer FOREIGN KEY (playerId) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS matchRounds (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  matchId INT UNSIGNED NOT NULL,
  roundNumber INT UNSIGNED NOT NULL,
  shooterId INT UNSIGNED NOT NULL,
  goalkeeperId INT UNSIGNED NOT NULL,
  result ENUM('GOAL','SAVED','MISS','POST','CROSSBAR') NOT NULL,
  shotTargetX FLOAT NOT NULL,
  shotTargetY FLOAT NOT NULL,
  goalkeeperTargetX FLOAT NOT NULL,
  goalkeeperTargetY FLOAT NOT NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uniqMatchRound (matchId, roundNumber),
  CONSTRAINT fkRoundsMatch FOREIGN KEY (matchId) REFERENCES matches (id) ON DELETE CASCADE,
  CONSTRAINT fkRoundsShooter FOREIGN KEY (shooterId) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fkRoundsKeeper FOREIGN KEY (goalkeeperId) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
